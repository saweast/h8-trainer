// Generates supabase/migrations/*_seed_exercises.sql from src/data/exercise-catalog.json.
// The JSON is the single source of truth: the app reads names (uk/en) from it by slug.
// Usage: node scripts/gen-exercise-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('..', import.meta.url)
export const SEED_FILE = fileURLToPath(new URL('supabase/migrations/20261104000004_seed_exercises.sql', root))
const CATALOG_FILE = fileURLToPath(new URL('src/data/exercise-catalog.json', root))

const WEIGHT_STEP = { machine: 5, cable: 5, barbell: 2.5, dumbbell: 2, bodyweight: 2.5, other: 2.5 }

export function defaultsFor({ muscle, equipment }) {
  const rest = muscle === 'core' ? 60 : equipment === 'barbell' ? 120 : 90
  return { weightStepKg: WEIGHT_STEP[equipment] ?? 2.5, restS: rest }
}

const q = (s) => `'${String(s).replaceAll("'", "''")}'`

export function buildSeedSql(catalog) {
  const slugs = new Set()
  const rows = catalog.map((ex) => {
    if (!/^[a-z0-9_]{2,60}$/.test(ex.slug)) throw new Error(`bad slug: ${ex.slug}`)
    if (slugs.has(ex.slug)) throw new Error(`duplicate slug: ${ex.slug}`)
    slugs.add(ex.slug)
    const d = defaultsFor(ex)
    // `name` holds the English name as a fallback; the app shows the translated name by slug.
    return `  (${q(ex.slug)}, ${q(ex.en)}, ${q(ex.muscle)}, ${q(ex.equipment)}, ${d.weightStepKg}, ${d.restS})`
  })
  return [
    '-- GENERATED by scripts/gen-exercise-seed.mjs from src/data/exercise-catalog.json. Do not edit by hand.',
    'insert into public.exercises (slug, name, muscle_group, equipment, weight_step_kg, default_rest_s) values',
    rows.join(',\n'),
    'on conflict (slug) do update set',
    '  name = excluded.name,',
    '  muscle_group = excluded.muscle_group,',
    '  equipment = excluded.equipment,',
    '  weight_step_kg = excluded.weight_step_kg,',
    '  default_rest_s = excluded.default_rest_s;',
    '',
  ].join('\n')
}

export function readCatalog() {
  return JSON.parse(readFileSync(CATALOG_FILE, 'utf8'))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalog = readCatalog()
  writeFileSync(SEED_FILE, buildSeedSql(catalog))
  console.log(`wrote ${catalog.length} exercises → ${SEED_FILE}`)
}
